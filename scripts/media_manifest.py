#!/usr/bin/env python3
"""Scan docs/play/assets/media/ and write media.js.

The manifest is a plain script, not JSON, so it loads from file:// as well as
from a server — no fetch, no CORS, no cache to bust. Any exercise id listed in it
is shown with that file instead of the SVG figure — in the workout stage, the
clip sheet and the library. Anything missing falls back to the figure, so a
partial set is fine and the app never breaks.

    python3 scripts/media_manifest.py

Precedence per id: mp4 → webm → webp → jpg → png
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.join(ROOT, "docs", "play", "assets", "media")
OUT = os.path.join(MEDIA, "media.js")

PREFERENCE = ["mp4", "webm", "webp", "jpg", "jpeg", "png", "gif"]
VIDEO = {"mp4", "webm"}

# ids the app knows about; anything else in the folder is ignored
IDS = ["plank", "deadbug", "birddog", "bicycle", "hollow",
       "warmup", "cooldown", "sideplank", "glutebridge", "superman"]


def main():
    found = {}
    if os.path.isdir(MEDIA):
        for name in sorted(os.listdir(MEDIA)):
            stem, ext = os.path.splitext(name)
            ext = ext.lower().lstrip(".")
            if stem in IDS and ext in PREFERENCE:
                rank = PREFERENCE.index(ext)
                if stem not in found or rank < found[stem][0]:
                    found[stem] = (rank, name, ext)

    manifest = {"generated": True}
    for ex_id in IDS:
        if ex_id in found:
            _, name, ext = found[ex_id]
            entry = {"src": "assets/media/" + name, "type": "video" if ext in VIDEO else "image"}
            # a still with the same id becomes the poster for a clip
            for still in ("jpg", "jpeg", "png", "webp"):
                candidate = os.path.join(MEDIA, ex_id + "." + still)
                if os.path.exists(candidate) and candidate.endswith(name) is False:
                    entry["poster"] = "assets/media/" + ex_id + "." + still
                    break
            manifest[ex_id] = entry

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by scripts/media_manifest.py — do not edit by hand. */\n")
        fh.write("(function (CF) {\n  CF.MEDIA_MANIFEST = ")
        json.dump(manifest, fh, indent=2)
        fh.write(";\n})(window.CF = window.CF || {});\n")

    count = len(manifest) - 1
    print("wrote", OUT, "—", count, "of", len(IDS), "assets present")
    for ex_id in IDS:
        if ex_id in manifest:
            print("  ", ex_id, "→", manifest[ex_id]["src"])
        else:
            print("  ", ex_id, "→ (figure)")


if __name__ == "__main__":
    main()
